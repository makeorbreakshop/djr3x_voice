//! `r3x-beats analyze [--force] FILE...`   analyse (cached) and print JSON lines
//! `r3x-beats compare [--music-dir D] [--out FILE.md]`
//!     re-analyse the library and compare against CantinaOS's librosa cache; tracks whose
//!     tempo differs beyond octave folding are listed for review (plan §9 Phase 4).

use std::path::{Path, PathBuf};
use std::time::Instant;

use anyhow::{bail, Result};
use r3x_beats::{default_cache_dir, librosa_cache_dir, BeatCache, ANALYZER_VERSION, LIBROSA_VERSION};

fn main() -> Result<()> {
    tracing_subscriber::fmt().with_env_filter(tracing_subscriber::EnvFilter::from_default_env()).with_writer(std::io::stderr).init();
    let mut args: Vec<String> = std::env::args().skip(1).collect();
    if args.is_empty() {
        bail!("usage: r3x-beats analyze [--force] FILE... | compare [--music-dir D] [--out FILE]");
    }
    let cmd = args.remove(0);
    let take = |args: &mut Vec<String>, flag: &str| -> Option<String> {
        let i = args.iter().position(|a| a == flag)?;
        args.remove(i);
        (i < args.len()).then(|| args.remove(i))
    };
    let cache = BeatCache::new(default_cache_dir());
    match cmd.as_str() {
        "analyze" => {
            let force = args.iter().any(|a| a == "--force");
            for f in args.iter().filter(|a| *a != "--force") {
                let t0 = Instant::now();
                let row = match cache.get_or_analyze(Path::new(f), force) {
                    Ok(i) => serde_json::json!({"path": f, "bpm": i.bpm, "first_beat_s": i.first_beat_s, "beats": i.beats.len(), "secs": t0.elapsed().as_secs_f64()}),
                    Err(e) => serde_json::json!({"path": f, "error": e.to_string()}),
                };
                println!("{row}");
            }
        }
        "compare" => {
            let dir = take(&mut args, "--music-dir").map(PathBuf::from).unwrap_or_else(default_music_dir);
            let out = take(&mut args, "--out");
            let report = compare(&dir, &cache, args.iter().any(|a| a == "--force"))?;
            match out {
                Some(p) => std::fs::write(&p, &report)?,
                None => print!("{report}"),
            }
        }
        other => bail!("unknown command {other}"),
    }
    Ok(())
}

fn default_music_dir() -> PathBuf {
    let d = std::env::var_os("MUSIC_DIR").map(PathBuf::from).unwrap_or_else(|| PathBuf::from(concat!(env!("CARGO_MANIFEST_DIR"), "/../../../audio/music")));
    r3x_beats::abspath(&d)
}

/// |a/b - k| minimised over octave factors k in {1/2, 1, 2}: the relative error left after
/// allowing an octave.
fn octave_error(a: f64, b: f64) -> (f64, f64) {
    [0.5, 1.0, 2.0]
        .iter()
        .map(|k| (((a / b) / k - 1.0).abs(), *k))
        .min_by(|x, y| x.0.total_cmp(&y.0))
        .unwrap()
}

fn compare(dir: &Path, ours: &BeatCache, force: bool) -> Result<String> {
    let theirs = BeatCache::librosa(librosa_cache_dir());
    let mut files: Vec<PathBuf> = std::fs::read_dir(dir)?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().and_then(|e| e.to_str()).is_some_and(|e| r3x_audio::decode::MUSIC_EXTENSIONS.contains(&e.to_ascii_lowercase().as_str())))
        .collect();
    files.sort();
    const TOL: f64 = 0.02;
    let (mut same, mut octave, mut differ, mut missing) = (0, 0, Vec::new(), 0);
    let mut rows = Vec::new();
    let t0 = Instant::now();
    for f in &files {
        let name = f.file_name().unwrap().to_string_lossy().into_owned();
        let r = ours.get_or_analyze(f, force);
        let l = theirs.get(f);
        let (rb, rphase) = r.as_ref().map(|i| (format!("{:.1}", i.bpm), format!("{:.3}", i.first_beat_s))).unwrap_or(("-".into(), "-".into()));
        let (lb, lphase) = l.as_ref().map(|i| (format!("{:.1}", i.bpm), format!("{:.3}", i.first_beat_s))).unwrap_or(("-".into(), "-".into()));
        let verdict = match (&r, &l) {
            (Ok(r), Some(l)) => {
                let (err, k) = octave_error(r.bpm, l.bpm);
                if err > TOL {
                    differ.push(name.clone());
                    format!("**differs** ({:+.1}%)", (r.bpm / l.bpm - 1.0) * 100.0)
                } else if k != 1.0 {
                    octave += 1;
                    format!("octave (x{k})")
                } else {
                    same += 1;
                    format!("same ({:+.1}%)", (r.bpm / l.bpm - 1.0) * 100.0)
                }
            }
            _ => {
                missing += 1;
                "not comparable".into()
            }
        };
        rows.push(format!("| {name} | {lb} | {rb} | {lphase} | {rphase} | {verdict} |"));
    }
    let mut md = String::new();
    md.push_str("# Beat analyser comparison: r3x-beats vs librosa cache\n\n");
    md.push_str(&format!(
        "Generated by `cargo run --release -p r3x-beats -- compare --out docs/plans/beat-analyzer-comparison.md` \
         over `{}` ({} files, {:.1} s including any analysis).\n\n",
        dir.display(),
        files.len(),
        t0.elapsed().as_secs_f64()
    ));
    md.push_str(&format!(
        "- Ours: `{ANALYZER_VERSION}` (librosa 0.11 `beat_track` ported to Rust: mel onset envelope, \
         autocorrelation tempogram with the 120 bpm log-normal prior, DP tracker; then the same \
         `refine_bpm`, fold into 70-180 and grid phase). Decode: symphonia + rubato to 22.05 kHz mono.\n\
         - Theirs: CantinaOS `{LIBROSA_VERSION}` cache (`~/.cache/dj-r3x/beats`).\n\
         - Verdict: *same* within {:.0}%; *octave* = equal after a x2 or x0.5 fold; **differs** = \
         apart even after octave folding - review these before beat-clocked shows rely on them.\n\n",
        TOL * 100.0
    ));
    md.push_str(&format!(
        "**Summary:** {same} same, {octave} octave-only, {} differ beyond octave folding, {missing} not comparable.\n\n",
        differ.len()
    ));
    if differ.is_empty() {
        md.push_str("No track differs beyond octave folding.\n\n");
    } else {
        md.push_str("Differ beyond octave folding (review):\n\n");
        for d in &differ {
            md.push_str(&format!("- {d}\n"));
        }
        md.push('\n');
    }
    md.push_str("| Track | librosa bpm | r3x bpm | librosa phase s | r3x phase s | Verdict |\n|---|---|---|---|---|---|\n");
    for r in rows {
        md.push_str(&r);
        md.push('\n');
    }
    Ok(md)
}
